export function buildUserMessageV2(params: {
  make: string;
  model: string;
  year?: number;
  mileageKm: number;
}): string {
  const make = params.make.trim();
  const model = params.model.trim();
  const yearLine =
    typeof params.year === "number" && Number.isFinite(params.year)
      ? `【年式（西暦）】\n${Math.round(params.year)}`
      : null;
  const mileageKm = Number.isFinite(params.mileageKm) ? Math.round(params.mileageKm) : 0;

  return [
    `【メーカー】\n${make}`,
    `【車種名】\n${model}`,
    ...(yearLine ? [yearLine] : []),
    `【走行距離】\n${mileageKm} km`,
    "上記の入力だけを使い、指定のJSON形式で出力してください。",
  ].join("\n\n");
}

